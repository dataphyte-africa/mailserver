<h2>Role of State Coordinators</h2>
<p>State Coordinators observe elections and recruit, coordinate, supervise and train election observers in their respective states. They act as the intermediary between observers and Dataphyte Foundation's designated focal person.</p>
<ul>
    <li>Observe the election at a designated polling unit and follow Dataphyte Foundation's observation methodology, reporting procedures and code of conduct.</li>
    <li>Recruit and select qualified observers using the Foundation's standard criteria, and conduct step-down training using provided materials.</li>
    <li>Monitor timely, accurate submissions from observers and provide regular updates about progress, incidents and coordination challenges.</li>
    <li>Resolve coordination challenges, maintain effective communication, and participate in required pre-election training and post-election debriefing.</li>
</ul>
<h2>Deliverables</h2>
<ul>
    <li>Attend mandatory State Coordinator training; recruit the number of observers authorised by Dataphyte Foundation; and train selected observers.</li>
    <li>Provide recruitment and selection plans, evidence of recruitment, training plans, and a training report with photographs, attendance and presentations.</li>
    <li>Submit incident updates and a financial report on funds spent coordinating observers.</li>
    <li>Submit election updates through the Nigeria Election Data Observatory (NEDO) app and ensure that recruited observers do the same.</li>
</ul>
<h2>Pre-election reporting</h2>
<p>Report relevant updates before election day, including deployment and arrival of materials and officials at the RAC centre, violence, party activities, vote trading and other incidents.</p>
<h2>Election day: before polling</h2>
<ul>
    <li>Arrive at the assigned polling unit by 6:45 AM. Check in with an identifying photograph of the polling unit.</li>
    <li>Report the arrival time of officials and materials, the presence and number of officials and security personnel, and when setup begins.</li>
    <li>Report when accreditation and voting begin and whether BVAS is available and functioning.</li>
</ul>
<h2>Election day: during voting</h2>
<ul>
    <li>Report security incidents, threats, disruption, vote trading or voter inducement as they occur.</li>
    <li>Record registered and accredited voter totals where available, and the total votes cast after counting.</li>
    <li>Report access barriers and available support for persons with disabilities, pregnant women, elderly voters and nursing mothers.</li>
    <li>Report other incidents, including delays, missing or incomplete materials, intimidation, ballot-secrecy breaches, medical emergencies and violence.</li>
</ul>
<h2>Election day: after voting</h2>
<ul>
    <li>Report when voting ends and counting begins, and submit results by party with a clear image of the result sheet.</li>
    <li>Report whether final polling-unit results are publicly displayed.</li>
    <li>Report results and access conditions at the assigned ward collation centre, and other relevant developments there.</li>
</ul>
<h2>Communication and data</h2>
<p>Remain reachable throughout the observation exercise. Answer calls from the coordination team and immediately report any security threat or request to leave the polling unit. All data collected during this exercise remains the property of Dataphyte Foundation.</p>
<h2>Payment conditions</h2>
<p>Payment is conditional on satisfactory participation and completion of mandatory deliverables. A State Coordinator's payment may be affected if required deliverables are not submitted. The payment amount and breakdown will be inserted only after confirmation.</p>
